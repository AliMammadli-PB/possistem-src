#!/usr/bin/env node
/**
 * Gives the market till the restaurant's printing.
 *
 * Market could not print. `MockPrinterProvider` kept the bytes in memory and
 * `FilePrinterProvider` wrote them to a .bin under userData - the till reported
 * a successful print and nothing came out. The live 1.4.4 build added a TCP
 * provider, so a LAN printer works if somebody types its IP by hand, but USB,
 * the Windows spooler, serial and LPT were never reachable, and nothing was
 * ever discovered automatically.
 *
 * The restaurant core already solves this and has been shipping it: USB
 * printer-class devices read by their IEEE-1284 id, spooler queues, COM, LPT,
 * and LAN boxes found through the ARP cache and a subnet sweep, then ranked and
 * probed with a real page until one accepts it - because the operator wants a
 * printer that works, not a report about printers.
 *
 * So it is ported rather than rewritten, and deliberately kept byte-identical
 * to its source apart from the namespace and the logger handle. Two pieces:
 *
 *   DeviceDiscovery - copied whole. Outside the standard library it touches
 *                     only a logger and the Win32 headers.
 *   RawSend         - the four transports lifted out of EscPos.cpp, which is
 *                     otherwise raster and code-page work market has no use
 *                     for, plus a dispatcher that picks one from the shape of
 *                     the target string.
 *
 * The logger needs no translation: market links the same spdlog and sets it as
 * the default logger, so the ported files ask for that instead of the
 * restaurant's named one and every `{}` and `{:02x}` in those log lines keeps
 * working.
 *
 * Re-running is safe and is the intended workflow: it regenerates the copies
 * from the restaurant source, so a fix there reaches the market till too.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MARKET = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REST = path.resolve(MARKET, '../restoranpos');

function must(cond, msg) {
  if (!cond) throw new Error(msg);
}
function read(p) {
  must(fs.existsSync(p), `missing source: ${p}`);
  return fs.readFileSync(p, 'utf8');
}
function write(p, body) {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, body);
  console.log(`  + ${path.relative(MARKET, p)}`);
}
function replaceOnce(src, from, to, what) {
  must(src.split(from).length - 1 === 1, `${what}: expected exactly one match`);
  return src.replace(from, to);
}

const BANNER = (from) => `/*
 * Ported from the restaurant core (${from}).
 *
 * Generated by scripts/port-printing-from-restaurant.mjs. Fix the restaurant
 * source and re-run rather than editing this copy, or the two drift and the
 * market till quietly loses a fix the restaurant got.
 */
`;

/** The restaurant's named spdlog logger, as market's default one. */
const LOGGER = `std::shared_ptr<spdlog::logger> logger() {
    // Market sets spdlog's default logger in market::logging::init, so the
    // ported code keeps its spdlog format strings and lands in market-core.log.
    return spdlog::default_logger();
}`;

// --- 1. discovery ---------------------------------------------------------
{
  let hpp = read(path.join(REST, 'native/core/include/pos/printing/DeviceDiscovery.hpp'));
  hpp = replaceOnce(hpp, 'namespace pos::printing {', 'namespace market::printing {', 'hpp namespace open');
  hpp = replaceOnce(hpp, '}  // namespace pos::printing', '}  // namespace market::printing', 'hpp namespace close');
  write(path.join(MARKET, 'native/core/include/market/printing/DeviceDiscovery.hpp'),
        BANNER('native/core/include/pos/printing/DeviceDiscovery.hpp') + hpp);

  let cpp = read(path.join(REST, 'native/core/src/printing/DeviceDiscovery.cpp'));
  cpp = replaceOnce(cpp, '#include "pos/printing/DeviceDiscovery.hpp"',
                    '#include "market/printing/DeviceDiscovery.hpp"', 'own header');
  cpp = replaceOnce(cpp, '#include "pos/Logging.hpp"', '#include <spdlog/spdlog.h>', 'logging header');
  cpp = replaceOnce(cpp, `std::shared_ptr<spdlog::logger> logger() {
    static auto log = logging::get("printer");
    return log;
}`, LOGGER, 'logger handle');
  cpp = replaceOnce(cpp, 'namespace pos::printing {', 'namespace market::printing {', 'cpp namespace open');
  cpp = replaceOnce(cpp, '}  // namespace pos::printing', '}  // namespace market::printing', 'cpp namespace close');

  must(!cpp.includes('pos::'), 'a pos:: reference survived the port');
  must(!cpp.includes('logging::get('), 'the restaurant logger handle survived');
  write(path.join(MARKET, 'native/core/src/printing/DeviceDiscovery.cpp'),
        BANNER('native/core/src/printing/DeviceDiscovery.cpp') + cpp);
}

// --- 2. transports --------------------------------------------------------
{
  const lines = read(path.join(REST, 'native/core/src/printing/EscPos.cpp')).split('\n');
  const at = (pred, what) => {
    const i = lines.findIndex(pred);
    must(i !== -1, `${what} not found in EscPos.cpp`);
    return i;
  };

  // Winsock init lives in EscPos's anonymous namespace, inside its own _WIN32
  // guard: lift the guarded block whole rather than the function alone.
  const wsStruct = at((l) => l === 'struct WinsockOnce {', 'WinsockOnce');
  const wsOpen = wsStruct - 1;
  must(lines[wsOpen] === '#ifdef _WIN32', 'WinsockOnce is no longer inside a _WIN32 guard');
  const wsClose = lines.indexOf('#endif', wsOpen);
  must(wsClose > wsOpen && wsClose - wsOpen < 40, 'the winsock guard has no plausible end');
  const winsock = lines.slice(wsOpen, wsClose + 1).join('\n');

  // The transports run from isNetworkPrinter to the end of the file; the last
  // line closes the restaurant namespace and is replaced by our own.
  const tStart = at((l) => l.startsWith('bool isNetworkPrinter'), 'the transport region');
  const tEnd = lines.lastIndexOf('}  // namespace pos::printing');
  must(tEnd > tStart, 'the namespace close is not after the transports');
  const transports = lines.slice(tStart, tEnd).join('\n').trimEnd();

  const body = `${winsock}\n\n${transports}`;
  // The lifted region must not reach back into the parts of EscPos left
  // behind, or it compiles against headers market does not have.
  for (const stray of ['ReceiptGraphics', 'RasterRenderer', 'EscPosOptions', 'appendCp857', 'PaperWidth']) {
    must(!body.includes(stray), `the lifted region references ${stray}`);
  }
  for (const fn of ['sendRawTcp', 'sendRawWindowsPrinter', 'sendRawUsbDevice', 'sendRawSerial',
                    'parseNetworkPrinter', 'parseUsbRawPrinter', 'parseSerialPrinter',
                    'parseWindowsPrinter', 'ensureWinsock']) {
    must(body.includes(fn), `${fn} is not in the lifted region`);
  }

  write(path.join(MARKET, 'native/core/include/market/printing/RawSend.hpp'), `${BANNER('native/core/src/printing/EscPos.cpp')}#pragma once

#include <cstdint>
#include <string>
#include <string_view>
#include <vector>

namespace market::printing {

bool isNetworkPrinter(std::string_view printerName);
bool parseNetworkPrinter(std::string_view printerName, std::string& host, int& port);
bool parseWindowsPrinter(std::string_view printerName, std::string& windowsName);
bool parseUsbRawPrinter(std::string_view printerName, std::string& devicePath);
bool parseSerialPrinter(std::string_view printerName, std::string& port, int& baud);

bool sendRawTcp(const std::string& host, int port, const std::vector<std::uint8_t>& payload,
                std::string& errorOut, int timeoutMs = 8000);
bool sendRawWindowsPrinter(const std::string& printerName, const std::vector<std::uint8_t>& payload,
                           std::string& errorOut);
bool sendRawUsbDevice(const std::string& devicePath, const std::vector<std::uint8_t>& payload,
                      std::string& errorOut);
bool sendRawSerial(const std::string& port, int baud, const std::vector<std::uint8_t>& payload,
                   std::string& errorOut);

/**
 * Sends to whatever the target names, choosing the transport from its shape:
 * \`tcp:host:port\`, a raw USB device path, \`serial:COM3@19200\`, or a Windows
 * queue name. Same order and same rules as the restaurant till.
 */
bool sendOnce(const std::string& target, const std::vector<std::uint8_t>& bytes,
              std::string& errorOut);

}  // namespace market::printing
`);

  write(path.join(MARKET, 'native/core/src/printing/RawSend.cpp'), `${BANNER('native/core/src/printing/EscPos.cpp')}#include "market/printing/RawSend.hpp"

#include <algorithm>
#include <memory>

#include <spdlog/spdlog.h>

#ifdef _WIN32
#ifndef WIN32_LEAN_AND_MEAN
#define WIN32_LEAN_AND_MEAN
#endif
// winsock2 must precede windows.h or the legacy winsock.h wins and the two
// headers redefine each other's socket types. Same ordering as EscPos.cpp.
#include <winsock2.h>
#include <ws2tcpip.h>
#include <windows.h>
#include <winspool.h>
#pragma comment(lib, "ws2_32.lib")
#endif

namespace market::printing {
namespace {

${LOGGER}

${winsock}

}  // namespace

${transports}

bool sendOnce(const std::string& target, const std::vector<std::uint8_t>& bytes,
              std::string& errorOut) {
    // Order matters: a target is tried as the most specific thing it could be.
    // A Windows queue name is last because it is the shape with no marker -
    // anything that did not look like the others is treated as a queue.
    std::string host;
    int port = 9100;
    if (parseNetworkPrinter(target, host, port)) return sendRawTcp(host, port, bytes, errorOut);

    std::string devicePath;
    if (parseUsbRawPrinter(target, devicePath)) return sendRawUsbDevice(devicePath, bytes, errorOut);

    std::string serialPort;
    int baud = 9600;
    if (parseSerialPrinter(target, serialPort, baud)) {
        return sendRawSerial(serialPort, baud, bytes, errorOut);
    }

    std::string windowsName;
    if (parseWindowsPrinter(target, windowsName)) {
        return sendRawWindowsPrinter(windowsName, bytes, errorOut);
    }

    errorOut = "Naməlum printer hədəfi: " + target;
    return false;
}

}  // namespace market::printing
`);
}

// --- 3. the libraries these need ------------------------------------------
{
  const cmakePath = path.join(MARKET, 'native/CMakeLists.txt');
  let cmake = read(cmakePath);
  if (!cmake.includes('setupapi')) {
    cmake = replaceOnce(cmake, `if(WIN32)
  target_link_libraries(market_core_lib PUBLIC bcrypt)
endif()`, `if(WIN32)
  # bcrypt was already here; the rest are what the ported printing needs:
  # setupapi and winspool to enumerate printers, iphlpapi for the ARP cache,
  # ws2_32 for the subnet probe and for talking to a LAN printer on 9100.
  target_link_libraries(market_core_lib PUBLIC bcrypt setupapi winspool iphlpapi ws2_32)
endif()`, 'CMake win32 block');
    fs.writeFileSync(cmakePath, cmake);
    console.log('  + CMake: setupapi winspool iphlpapi ws2_32');
  } else {
    console.log('  = CMake libraries');
  }
}

console.log('\nported. Rebuild the market core to pick it up.');
