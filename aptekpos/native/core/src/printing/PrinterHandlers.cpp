void registerPrinterHandlers(ipc::StdioServer& server, db::Database& db) {
    // Local links only. This runs whenever the settings screen opens, and a LAN
    // sweep there would make it feel broken for six seconds.
    server.on("printer.list", [&db](const Json&) {
        Json printers = Json::array();
        for (const auto& candidate : rankPrinterCandidates(currentTarget(db), false)) {
            printers.push_back(candidateToJson(candidate));
        }
        return Json{{"printers", printers}, {"current", currentTarget(db)}};
    });

    // The whole search, network included, then a real page to each candidate in
    // rank order until one takes it. The first that prints becomes the till's
    // printer - the operator gets a working printer rather than a list to read.
    server.on("printer.detect", [&db](const Json& p) {
        requirePermission(db, p, "MANAGE_SETTINGS");

        const bool probe = p.value("probe", true);
        const auto current = currentTarget(db);
        const auto candidates = rankPrinterCandidates(current, true);

        Json listed = Json::array();
        for (const auto& candidate : candidates) listed.push_back(candidateToJson(candidate));

        Json probed = Json::array();
        std::string chosen;
        if (probe) {
            for (const auto& candidate : candidates) {
                if (candidate.link == PrinterLink::Virtual) continue;
                if (candidate.score <= 0) continue;

                const auto started = elapsedMs();
                std::string error;
                const bool ok = sendOnce(candidate.target,
                                         probePage(candidate.displayName.empty() ? candidate.target
                                                                                 : candidate.displayName),
                                         error);
                probed.push_back(Json{{"target", candidate.target},
                                      {"displayName", candidate.displayName},
                                      {"ok", ok},
                                      {"error", error},
                                      {"durationMs", elapsedMs() - started}});
                if (ok) {
                    chosen = candidate.target;
                    break;
                }
            }
        }

        if (!chosen.empty()) {
            rememberTarget(db, chosen);
            auditPrinter(db, p.value("actorId", "system"), "PRINTER_AUTODETECT", chosen);
            for (auto& candidate : listed) {
                candidate["isCurrent"] = candidate.value("target", "") == chosen;
            }
        }

        return Json{{"printers", listed},
                    {"current", chosen.empty() ? current : chosen},
                    {"chosen", chosen.empty() ? Json(nullptr) : Json(chosen)},
                    {"probed", probed}};
    });

    server.on("printer.setTarget", [&db](const Json& p) {
        requirePermission(db, p, "MANAGE_SETTINGS");
        const auto target = p.value("target", std::string{});
        if (target.empty()) throw PosError("E_VALIDATION", "target required");
        rememberTarget(db, target);
        auditPrinter(db, p.value("actorId", "system"), "PRINTER_SET_TARGET", target);
        return Json{{"ok", true}, {"current", target}};
    });

    // Electron builds the ESC/POS bytes and hands them here. `target` overrides
    // the configured one so a test page can go to a printer before it is chosen.
    server.on("printer.send", [&db](const Json& p) {
        auto target = p.value("target", std::string{});
        if (target.empty()) target = currentTarget(db);
        if (target.empty()) {
            throw PosError("PRINTER_NOT_CONFIGURED",
                           "Printer seçilməyib — Parametrlərdən printeri tapın", false);
        }

        const auto bytes = payloadBytes(p);
        std::string error;
        if (!sendOnce(target, bytes, error)) {
            // Retryable: the usual cause is a printer that is off or unplugged,
            // and the till should offer the operator another go rather than
            // treating a receipt as permanently lost.
            throw PosError("PRINTER_SEND_FAILED", error.empty() ? "Printerə göndərilmədi" : error, true,
                           Json{{"target", target}});
        }
        return Json{{"ok", true}, {"target", target}, {"bytes", bytes.size()}};
    });
}

