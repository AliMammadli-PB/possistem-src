using Json = nlohmann::json;

/** Monotonic, for probe durations only - never for a stored timestamp. */
std::int64_t elapsedMs() {
    return std::chrono::duration_cast<std::chrono::milliseconds>(
               std::chrono::steady_clock::now().time_since_epoch())
        .count();
}

/**
 * An audit row. The id and the timestamp are generated by sqlite rather than
 * borrowed from RetailOps.cpp, whose helpers are file-local.
 */
void auditPrinter(db::Database& db, const std::string& actorId, const std::string& action,
                  const std::string& detail) {
    sqlite3_stmt* stmt = nullptr;
    sqlite3_prepare_v2(db.raw(),
                       "INSERT INTO audit_logs(id, created_at, actor_id, action, detail) "
                       "VALUES ('audit_' || lower(hex(randomblob(8))), "
                       "        CAST(strftime('%s','now') AS INTEGER) * 1000, ?, ?, ?)",
                       -1, &stmt, nullptr);
    sqlite3_bind_text(stmt, 1, actorId.c_str(), -1, SQLITE_TRANSIENT);
    sqlite3_bind_text(stmt, 2, action.c_str(), -1, SQLITE_TRANSIENT);
    sqlite3_bind_text(stmt, 3, detail.c_str(), -1, SQLITE_TRANSIENT);
    sqlite3_step(stmt);
    sqlite3_finalize(stmt);
}

Json printerConfig(db::Database& db) {
    const auto raw = db.queryText("SELECT value FROM settings WHERE key = 'printerConfig'");
    if (raw.empty()) return Json::object();
    try {
        auto parsed = Json::parse(raw);
        return parsed.is_object() ? parsed : Json::object();
    } catch (...) {
        return Json::object();
    }
}

/** The configured destination, empty when the till has never chosen one. */
std::string currentTarget(db::Database& db) {
    const auto config = printerConfig(db);
    const auto target = config.value("target", std::string{});
    return target == "auto" ? std::string{} : target;
}

void rememberTarget(db::Database& db, const std::string& target) {
    auto config = printerConfig(db);
    config["target"] = target;
    const auto value = config.dump();

    sqlite3_stmt* stmt = nullptr;
    sqlite3_prepare_v2(db.raw(),
                       "INSERT INTO settings(key, value) VALUES ('printerConfig', ?) "
                       "ON CONFLICT(key) DO UPDATE SET value = excluded.value",
                       -1, &stmt, nullptr);
    sqlite3_bind_text(stmt, 1, value.c_str(), -1, SQLITE_TRANSIENT);
    sqlite3_step(stmt);
    sqlite3_finalize(stmt);
}

/**
 * A short page proving the device is real and prints legibly.
 *
 * Deliberately not a blank feed: detection picks the first candidate that
 * accepts bytes, and a spooler queue pointed at a PDF accepts them happily.
 * The operator looking at the counter is the last check, so the page has to
 * say which of the candidates printed it.
 */
std::vector<std::uint8_t> probePage(const std::string& label) {
    std::vector<std::uint8_t> out{0x1B, 0x40, 0x1B, 0x61, 0x01};  // init, centre
    const std::string text = "AptekPos\nPRINTER TESTI\n\n" + label + "\n\n";
    out.insert(out.end(), text.begin(), text.end());
    out.insert(out.end(), {0x1B, 0x64, 0x04});  // feed 4
    out.insert(out.end(), {0x1D, 0x56, 0x00});  // full cut
    return out;
}

/** A candidate in the shape the settings screen consumes. */
Json candidateToJson(const PrinterCandidate& candidate) {
    std::string model = candidate.model;
    if (!candidate.manufacturer.empty()) {
        model = model.empty() ? candidate.manufacturer : candidate.manufacturer + " " + model;
    }
    const auto status = decodeEscPosStatus(candidate.statusByte);

    return Json{{"target", candidate.target},
                {"displayName", candidate.displayName},
                {"connection", std::string(linkToString(candidate.link))},
                {"model", model},
                {"commandSet", candidate.commandSet},
                {"vendorId", candidate.vendorId},
                {"productId", candidate.productId},
                {"port", candidate.port},
                {"driver", candidate.driver},
                {"ipAddress", candidate.ipAddress},
                {"macAddress", candidate.macAddress},
                {"escposConfirmed", candidate.escposConfirmed},
                {"score", candidate.score},
                {"isCurrent", candidate.isCurrent},
                {"status", candidate.escposConfirmed && !status.online ? "offline" : "ready"}};
}

/** `{"bytes": [27, 64, ...]}` - a JSON array, so no encoding lives here. */
std::vector<std::uint8_t> payloadBytes(const Json& payload) {
    if (!payload.contains("bytes") || !payload["bytes"].is_array()) {
        throw PosError("E_VALIDATION", "bytes array required");
    }
    std::vector<std::uint8_t> bytes;
    bytes.reserve(payload["bytes"].size());
    for (const auto& value : payload["bytes"]) {
        if (!value.is_number_integer()) throw PosError("E_VALIDATION", "bytes must be integers");
        const auto byte = value.get<std::int64_t>();
        if (byte < 0 || byte > 255) throw PosError("E_VALIDATION", "byte out of range");
        bytes.push_back(static_cast<std::uint8_t>(byte));
    }
    if (bytes.empty()) throw PosError("E_VALIDATION", "nothing to print");
    return bytes;
}

