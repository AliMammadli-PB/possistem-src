import fs from 'node:fs';
import {transform} from 'esbuild';
const code=fs.readFileSync(new URL('./lib/vendor/qrcodegen.ts',import.meta.url),'utf8');
const compiled=await transform(code,{loader:'ts',target:'es2022',legalComments:'inline'});
fs.writeFileSync(new URL('./lib/ps-qr.mjs',import.meta.url), '// Generated by build-receipt-qr.mjs. Nayuki QR generator; MIT license in vendor/qrcodegen.ts.\n'+compiled.code+`
export function psQrMatrix(text, forcedMask) {
  const bytes = Array.from(new TextEncoder().encode(String(text ?? '')));
  if (!bytes.length) return [];
  const qr = qrcodegen.QrCode.encodeSegments([qrcodegen.QrSegment.makeBytes(bytes)],qrcodegen.QrCode.Ecc.MEDIUM,1,40,forcedMask ?? -1,false);
  return Array.from({length:qr.size},(_,y)=>Array.from({length:qr.size},(_,x)=>qr.getModule(x,y)));
}
export function psQrDataUrl(text) {
  const m=psQrMatrix(text); if(!m.length)return '';
  const n=m.length+8; let d='';
  m.forEach((row,y)=>row.forEach((on,x)=>{if(on)d+='M'+(x+4)+' '+(y+4)+'h1v1h-1z';}));
  return 'data:image/svg+xml;charset=utf-8,'+encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 '+n+' '+n+'" shape-rendering="crispEdges"><rect width="100%" height="100%" fill="white"/><path fill="black" d="'+d+'"/></svg>');
}
`);
