#!/usr/bin/env node
/**
 * Upload full project source to the Linux server (no node_modules / release artifacts).
 *
 *   POS_SSH_PASS='…' node scripts/upload-source-linux.mjs
 */
import { Client } from 'ssh2';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HOST = process.env.POS_SSH_HOST ?? '169.58.242.152';
const USER = process.env.POS_SSH_USER ?? 'server';
const PASS = process.env.POS_SSH_PASS ?? '';
const REMOTE_DIR = process.env.POS_SRC_DIR ?? '/home/server/restoran-pos';

if (!/^\/home\/server\/restoran-pos(?:\.next-1\.2\.4-[0-9TZ]+)?$/.test(REMOTE_DIR)) {
  console.error(`refusing unsafe POS_SRC_DIR: ${REMOTE_DIR}`);
  process.exit(1);
}

if (!PASS) {
  console.error('POS_SSH_PASS is required');
  process.exit(1);
}

function log(msg) {
  process.stdout.write(`[upload-source] ${msg}\n`);
}

function sudoBash(script) {
  const escapedPass = PASS.replace(/'/g, `'\\''`);
  const b64 = Buffer.from(script, 'utf8').toString('base64');
  return `printf '%s\\n' '${escapedPass}' | sudo -S -p '' bash -lc ${JSON.stringify(
    `echo ${b64} | base64 -d | bash -s`,
  )}`;
}

function exec(conn, command, timeoutMs = 600_000) {
  return new Promise((resolve, reject) => {
    conn.exec(command, { pty: true }, (err, stream) => {
      if (err) return reject(err);
      let stdout = '';
      let stderr = '';
      const timer = setTimeout(() => {
        stream.close();
        reject(new Error(`timeout\n${stdout || stderr}`));
      }, timeoutMs);
      stream.on('data', (d) => {
        stdout += d.toString();
        process.stdout.write(d.toString());
      });
      stream.stderr.on('data', (d) => {
        stderr += d.toString();
        process.stderr.write(d.toString());
      });
      stream.on('close', (code) => {
        clearTimeout(timer);
        resolve({ code: code ?? 0, stdout, stderr });
      });
    });
  });
}

function sftpPut(conn, localPath, remotePath) {
  return new Promise((resolve, reject) => {
    conn.sftp((err, sftp) => {
      if (err) return reject(err);
      sftp.fastPut(localPath, remotePath, (e) => (e ? reject(e) : resolve()));
    });
  });
}

async function main() {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'pos-src-'));
  const tarPath = path.join(tmp, 'restoran-pos-src.tgz');

  log('packing source (excluding heavy/build artifacts)');
  const excludes = [
    '--exclude=node_modules',
    '--exclude=**/node_modules',
    '--exclude=.git',
    '--exclude=release',
    '--exclude=release-*',
    '--exclude=out',
    '--exclude=dist',
    '--exclude=**/dist',
    // NOT `--exclude=build`: tar matches that against every path component, so
    // it dropped the top-level build/ directory too - which is not build output
    // at all but the application icon electron-builder needs. Packaging on a
    // fresh clone then failed with `cannot find "build/icon.ico"`. Only the
    // C++ build trees are artifacts.
    '--exclude=native/build',
    '--exclude=native/build-*',
    // Regenerated by scripts/gen-icons.mjs from build/icon.png.
    '--exclude=build/icon-*.png',
    '--exclude=test-results',
    '--exclude=logs',
    '--exclude=*.log',
    '--exclude=.data',
    '--exclude=control/.data',
    '--exclude=*.tsbuildinfo',
    '--exclude=.cursor',
    '--exclude=playwright-report',
    // The session secret and activation pepper. The remote tree is wiped before
    // extraction, so uploading without this exclusion does not just leak the
    // file - it replaces the server's own copy with the developer's.
    '--exclude=.env',
    '--exclude=.env.*',
    '--exclude=**/.env',
    '--exclude=**/.env.*',
  ].join(' ');

  // Prefer bsdtar/tar on Windows (Git Bash / tar.exe)
  execSync(`tar -czf "${tarPath}" ${excludes} .`, {
    cwd: ROOT,
    stdio: 'inherit',
    shell: true,
  });

  const sizeMb = (fs.statSync(tarPath).size / (1024 * 1024)).toFixed(1);
  log(`archive ${sizeMb} MB → ${HOST}:${REMOTE_DIR}`);

  const conn = new Client();
  await new Promise((resolve, reject) => {
    conn
      .on('ready', resolve)
      .on('error', reject)
      .connect({ host: HOST, port: 22, username: USER, password: PASS, readyTimeout: 30_000 });
  });

  const remoteTar = `/tmp/restoran-pos-src-${Date.now()}.tgz`;
  log('uploading');
  await sftpPut(conn, tarPath, remoteTar);

  log('extracting on server');
  const r = await exec(
    conn,
    sudoBash(`
set -e
case '${REMOTE_DIR}' in
  /home/server/restoran-pos|/home/server/restoran-pos.next-1.2.4-*) ;;
  *) echo UNSAFE_REMOTE_DIR >&2; exit 90 ;;
esac
if [ -L '${REMOTE_DIR}' ]; then echo REMOTE_DIR_IS_SYMLINK >&2; exit 91; fi
mkdir -p ${REMOTE_DIR}
# The server's own .env (session secret, activation pepper) is never shipped in
# the archive, so it has to survive the wipe on its own or the control plane
# loses its credentials on every source upload.
KEEP=$(mktemp -d)
cd ${REMOTE_DIR}
find . -maxdepth 2 \\( -name '.env' -o -name '.env.*' \\) -exec cp -a --parents {} "\$KEEP"/ \\; 2>/dev/null || true
cd /
# wipe previous tree but keep the directory
find ${REMOTE_DIR} -mindepth 1 -maxdepth 1 -exec rm -rf {} +
tar -xzf ${remoteTar} -C ${REMOTE_DIR}
cp -a "\$KEEP/." ${REMOTE_DIR}/ 2>/dev/null || true
rm -rf "\$KEEP"
chown -R ${USER}:${USER} ${REMOTE_DIR}
rm -f ${remoteTar}
echo SRC_OK
du -sh ${REMOTE_DIR}
ls -la ${REMOTE_DIR} | head -40
`),
    600_000,
  );

  conn.end();
  try {
    fs.rmSync(tmp, { recursive: true, force: true });
  } catch {
    /* ignore */
  }

  if (r.code !== 0 || !r.stdout.includes('SRC_OK')) {
    console.error('upload failed');
    process.exit(1);
  }
  log(`done → ${USER}@${HOST}:${REMOTE_DIR}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
