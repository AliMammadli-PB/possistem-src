#!/usr/bin/env bash
# Launches Market POS from the repository: the latest renderer and core, every
# time. The core is the Windows build (mingw) run under Wine.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MARKET="$ROOT/../marketpos"
ELECTRON="$ROOT/node_modules/.bin/electron"
WRAPPER="$MARKET/native/build/market-pos-core"

export ELECTRON_OZONE_PLATFORM_HINT="${ELECTRON_OZONE_PLATFORM_HINT:-x11}"
export WINEPREFIX="${XDG_DATA_HOME:-$HOME/.local/share}/possistem/wine"
export WINEDEBUG=-all
mkdir -p "$WINEPREFIX"

cd "$ROOT"
# Incremental: ninja only recompiles what changed since the last launch.
node scripts/build-market-core.mjs
npx vite build --config ../marketpos/vite.config.ts --logLevel warn

cat > "$WRAPPER" <<'WRAP'
#!/usr/bin/env bash
# Generated by scripts/launch-market-linux.sh - the Windows core under Wine.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export WINEPREFIX="${WINEPREFIX:-${XDG_DATA_HOME:-$HOME/.local/share}/possistem/wine}"
export WINEDEBUG="${WINEDEBUG:--all}"
exec wine "$HERE/market-pos-core.exe" "$@"
WRAP
chmod +x "$WRAPPER"
export MARKET_POS_CORE_PATH="$WRAPPER"

cd "$MARKET"
exec "$ELECTRON" . --no-sandbox --ozone-platform=x11 "$@"
